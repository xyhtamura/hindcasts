'use strict';
const assert=require('node:assert/strict'),path=require('node:path'),fs=require('node:fs'),os=require('node:os');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.PLAYWRIGHT_PATH||'playwright');
const Rack=require('./rack.js'),WAV=require('./wav.cjs');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.EDGE_PATH||'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
 try{
  const page=await browser.newPage({acceptDownloads:true,viewport:{width:1440,height:1100}}),errors=[];page.setDefaultTimeout(10000);page.on('pageerror',e=>{errors.push(e.message);console.error('Page error:',e.message);});
  await page.route('https://**/*',r=>r.abort());
  await page.goto(process.env.RACK_URL||pathToFileURL(path.join(__dirname,'rack.html')).href);
  await page.waitForFunction(()=>document.querySelector('#editor').dataset.cell==='sounder1');
  const rate=await page.evaluate(()=>new AudioContext().sampleRate);
  const audio={sampleRate:rate,channels:[Float32Array.from({length:5003},(_,i)=>.1*Math.sin(i*.07)),Float32Array.from({length:5003},(_,i)=>-.1*Math.sin(i*.07))]};
  await page.locator('#recording').setInputFiles({name:'probe.wav',mimeType:'audio/wav',buffer:WAV.encode(audio)});
  await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Loaded'));
  const frame=page.frameLocator('#editor');
  await frame.locator('#mmakeup').fill('6');await frame.locator('#mmakeup').dispatchEvent('input');
  await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Rack changed'));
  await page.locator('#add').click();await page.waitForFunction(()=>document.querySelector('#editor').dataset.cell==='sounder2');
  assert.match(await page.locator('#upstream').textContent(),/sounder1/);
  const upstreamChart=await frame.locator('#chart').evaluate(c=>c.toDataURL());
  await page.locator('.cell').first().getByLabel('Bypass').check();
  await page.locator('.cell').nth(1).locator(':scope > button').click();
  await page.waitForTimeout(150);
  const bypassChart=await frame.locator('#chart').evaluate(c=>c.toDataURL());assert.notEqual(upstreamChart,bypassChart);
  await page.locator('.cell').first().getByLabel('Bypass').uncheck();
  await page.locator('.cell').nth(1).locator(':scope > button').click();await page.waitForTimeout(150);
  assert.equal(await frame.locator('#chart').evaluate(c=>c.toDataURL()),upstreamChart);
  await frame.locator('#mmakeup').fill('-2');await frame.locator('#mmakeup').dispatchEvent('input');
  await page.locator('.cell').nth(1).getByRole('button',{name:'Duplicate',exact:true}).click();
  assert.equal(await page.locator('.cell').count(),3);
  await page.locator('.cell').nth(2).getByRole('button',{name:'Up',exact:true}).click();
  await page.locator('.cell').nth(1).getByRole('button',{name:'Remove',exact:true}).click();
  assert.equal(await page.locator('.cell').count(),2);
  await page.locator('.cell').nth(1).getByLabel('Cell mix').fill('0.5');await page.locator('.cell').nth(1).getByLabel('Cell mix').dispatchEvent('change');
  await page.locator('#master-gain').fill('2');await page.locator('#master-gain').dispatchEvent('change');
  await page.locator('#master-ceiling').fill('-18');await page.locator('#master-ceiling').dispatchEvent('change');
  async function download(button){const pending=page.waitForEvent('download');await page.locator(button).click();return fs.readFileSync(await (await pending).path());}
  const saved=JSON.parse((await download('#save')).toString());Rack.validate(saved);assert.equal(saved.nodes.length,2);assert.equal(saved.nodes[0].state.global.makeupDb,6);assert.equal(saved.nodes[1].state.global.makeupDb,-2);assert.equal(saved.nodes[1].mix,.5);
  await page.locator('#process').click();await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Processed'));
  const expected=Rack.render(audio,saved),output=WAV.decode(await download('#export'));
  assert.deepEqual(output.channels,expected.channels);
  assert.ok(expected.report.limitedSamples>0);
  await page.locator('#stage').selectOption(saved.nodes[0].id);const stage=WAV.decode(await download('#export'));assert.deepEqual(stage.channels,expected.cache.get(saved.nodes[0].id));
  await page.waitForFunction(()=>document.querySelector('#player').readyState>=2);
  assert.ok(Math.abs(await page.locator('#player').evaluate(a=>a.duration)-5003/rate)<.001);
  await page.locator('#player').evaluate(a=>a.play());
  await page.waitForFunction(()=>document.querySelector('#player').currentTime>0);
  await page.locator('#player').evaluate(a=>a.pause());
  await page.locator('.cell').first().getByLabel('Bypass').check();assert.equal(await page.locator('#export').isDisabled(),true);assert.equal(await page.locator('#player').getAttribute('src'),null);
  await page.locator('#recipe-file').setInputFiles({name:'rack.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(saved))});
  await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Rack loaded'));
  const roundtrip=JSON.parse((await download('#save')).toString());assert.deepEqual(roundtrip,saved);
  const branched=Rack.chain([Rack.defaultState(),Rack.defaultState()]);branched.nodes[1].input='source';
  await page.locator('#recipe-file').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(branched))});
  await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Rack not loaded'));
  assert.deepEqual(JSON.parse((await download('#save')).toString()),saved);
  const screenshotDir=process.env.SCREENSHOT_DIR||os.tmpdir();
  await page.screenshot({path:path.join(screenshotDir,'sounder-rack-desktop.png'),fullPage:true,timeout:10000});
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(150);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:path.join(screenshotDir,'sounder-rack-mobile.png'),fullPage:true,timeout:10000});
  assert.deepEqual(errors,[]);
  console.log('PASS: rack cell edits/reordering, upstream histogram, float WAV output/stage parity, invalidation, recipe round trip/rejection, responsive width');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
